// Shared queue + vote-skip.  node e2e/hangout.mjs
import { createRequire } from "node:module";
const { chromium } = createRequire("/opt/node22/lib/node_modules/")("playwright");
const BASE = process.env.BASE ?? "http://localhost:5173";
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? "/opt/pw-browsers/chromium-1194/chrome-linux/chrome", args: ["--autoplay-policy=no-user-gesture-required"] });
const host = await (await browser.newContext()).newPage();
const guest = await (await browser.newContext()).newPage();
await host.goto(BASE);
await host.getByLabel("Your name").fill("Host");
await host.getByRole("radio", { name: /Hangout/ }).click();
await host.getByText("Create room").click();
await host.waitForURL(/\/room\//);
const code = host.url().split("/room/")[1];
await guest.goto(`${BASE}/join/${code}`);
await guest.getByLabel("Your name").fill("Gus");
await guest.getByRole("button", { name: "Join", exact: true }).click();
await guest.waitForURL(/\/room\//);
for (const p of [host, guest]) await p.getByRole("button", { name: "Queue", exact: true }).click();
await host.getByPlaceholder(/Add a YouTube link/).fill(`${BASE}/demo.webm?a=1`);
await host.getByRole("button", { name: "Add", exact: true }).click();
await guest.getByPlaceholder(/Add a YouTube link/).fill(`${BASE}/demo.webm?b=2`);
await guest.getByRole("button", { name: "Add", exact: true }).click();
await guest.getByText(/Now playing/).waitFor({ timeout: 5000 });
await guest.getByText(/Up next \(1\)/).waitFor({ timeout: 5000 });
await guest.waitForSelector("video");
await guest.getByText(/Vote skip/).click();
await host.getByText(/b=2/).first().waitFor({ timeout: 5000 });
await host.getByText(/Up next \(0\)/).waitFor({ timeout: 5000 });
console.log("QUEUE + SKIP VOTE OK");
await browser.close();
