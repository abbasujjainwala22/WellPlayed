// Guest asks for a break, host approves, both see the countdown.  node e2e/break.mjs
import { createRequire } from "node:module";
const { chromium } = createRequire("/opt/node22/lib/node_modules/")("playwright");
const BASE = process.env.BASE ?? "http://localhost:5173";
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const host = await (await browser.newContext()).newPage();
const guest = await (await browser.newContext()).newPage();
await host.goto(BASE);
await host.getByLabel("Your name").fill("Host");
await host.getByText("Create room").click();
await host.waitForURL(/\/room\//);
const code = host.url().split("/room/")[1];
await guest.goto(`${BASE}/join/${code}`);
await guest.getByLabel("Your name").fill("Uzi");
await guest.getByRole("button", { name: "Join", exact: true }).click();
await guest.waitForURL(/\/room\//);
await guest.getByText("I need a break").click();
await host.getByText("Approve").click();
await guest.getByText(/Resuming in/).waitFor({ timeout: 5000 });
await host.getByText(/Uzi needs a break/).waitFor({ timeout: 5000 });
console.log("BREAK FLOW OK");
await browser.close();
